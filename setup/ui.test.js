// Installer states without Adobe apps or installation privileges.
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const { JSDOM } = require("jsdom");
const dom = new JSDOM(fs.readFileSync(path.join(__dirname, "setup.html"), "utf8"), { runScripts: "outside-only" });
const w = dom.window, sent = [];
let receive;
w.chrome = { webview: { postMessage: (m) => sent.push(m), addEventListener: (_, fn) => (receive = fn) } };
w.matchMedia = () => ({ matches: true });
w.requestAnimationFrame = () => 0;
w.HTMLCanvasElement.prototype.getContext = () => ({ drawImage() {} });
w.createStage = () => ({ setLook() {}, start() {} });
w.eval(fs.readFileSync(path.join(__dirname, "../photoshop/looks.js"), "utf8"));
w.eval([...w.document.scripts].find((s) => !s.src).textContent);
const $ = (id) => w.document.getElementById(id);
const message = (data) => receive({ data });
const state = (ps, ai, ae, blocked = false, cc = true) => message({ type: "state", version: "0.8.0", cc, blocked,
  ps: { found: ps, running: false }, ai: { found: ai, running: false }, ae: { found: ae, running: false } });
state(false, false, false);
assert($("go").disabled && $("aeRow").hidden);
state(true, true, false);
assert(!$("go").disabled && $("aeRow").hidden);
state(true, false, true, true);
assert($("go").disabled);
state(true, true, true, false, false);
assert($("go").disabled);
state(true, true, true);
assert(!$("go").disabled && !$("aeRow").hidden);
$("go").click();
assert(sent.includes("install") && $("go").disabled);
for (const app of ["ai", "ae", "ps"]) message({ type: "step", app, status: "done", text: "Installed" });
message({ type: "finished" });
assert.strictEqual($("go").textContent, "Done");
assert.strictEqual($("progress").getAttribute("aria-valuenow"), "100");
assert.strictEqual($("step3").getAttribute("aria-current"), "step");
$("go").click();
assert(sent.includes("close"));
message({ type: "step", app: "ae", status: "fail", text: "Close After Effects and retry." });
message({ type: "finished" });
assert.strictEqual($("go").textContent, "Install again");
assert($("aeSt").textContent.includes("Close After Effects"));
$("go").click();
assert($("go").disabled && $("go").textContent === "Installing…");
dom.window.close();
console.log("setup UI: detection, blocked apps, progress, success and retry passed");
